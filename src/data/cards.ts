function build(): Card[] {
  const cards: Card[] = MAJOR.map((r, i) => ({
    id: `major-${String(i).padStart(2, '0')}`,
    arcana: 'major',
    number: i,
    name: r[0],
    nameEn: r[1],
    keywordsUpright: r[2],
    keywordsReversed: r[3],
    upright: r[4],
    reversed: r[5],
    tip: r[6],
    status: 'draft',
  }));
  for (const suit of Object.keys(MINOR) as Suit[]) {
    MINOR[suit].forEach((r, i) => {
      const n = i + 1;
      cards.push({
        id: `${suit}-${String(n).padStart(2, '0')}`,
        arcana: 'minor',
        number: n,
        suit,
        name: `${SUIT_INFO[suit].name}${RANK_NAMES[n]}`,
        nameEn: `${RANK_EN[n]} of ${SUIT_INFO[suit].nameEn}`,
        keywordsUpright: r[2],
        keywordsReversed: r[3],
        upright: r[4],
        reversed: r[5],
        tip: r[6],
        status: 'draft',
      });
    });
  }
  return cards;
}

export const CARDS: readonly Card[] = build();
const BY_ID = new Map(CARDS.map((c) => [c.id, c]));

export function getCard(id: string): Card {
  const c = BY_ID.get(id);
  if (!c) throw new Error(`unknown card ${id}`);
  return c;
}

const ROMAN = ['0', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII', 'XIII', 'XIV', 'XV', 'XVI', 'XVII', 'XVIII', 'XIX', 'XX', 'XXI'];
export function roman(n: number): string {
  return ROMAN[n] ?? String(n);
}
